// Pi coding agent adapter (dossier pi.md). Pure: builds a plan, touches nothing.
// Mechanism (section 3): a launcher-owned extension file loaded with `-e` registers the
// "omniroute" provider; the key travels only in env OMNIROUTE_API_KEY (Pi's $NAME interpolation).

import {
  LaunchError,
  NO_AUTH_SENTINEL,
  createPlan,
  defineAdapter,
  ensureV1,
  findFlag,
  injectRows,
  rowLabel,
} from "../contract.mjs";

const DISPLAY_NAME = "Pi";
const MIN_VERSION = "0.85.1";
const MIN_CONTEXT = 32000;
const INSTALL_HINT = "npm install -g --ignore-scripts @earendil-works/pi-coding-agent";

function parseVersion(text) {
  const match = /(\d+)\.(\d+)\.(\d+)/.exec(String(text ?? ""));
  return match ? [Number(match[1]), Number(match[2]), Number(match[3])] : null;
}

function compareVersions(a, b) {
  for (let i = 0; i < 3; i += 1) {
    if (a[i] !== b[i]) return a[i] < b[i] ? -1 : 1;
  }
  return 0;
}

function buildModel(row) {
  const capabilities = row.capabilities ?? [];
  const knownContext = typeof row.contextTokens === "number";
  const contextWindow = knownContext ? row.contextTokens : 128000;
  const maxTokens =
    row.maxOutputTokens ?? (knownContext ? Math.min(32000, Math.floor(contextWindow / 4)) : 16384);
  return {
    id: row.id,
    name: rowLabel(row),
    reasoning: capabilities.includes("reasoning"),
    input: capabilities.includes("vision") ? ["text", "image"] : ["text"],
    cost: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0 },
    contextWindow,
    maxTokens,
  };
}

function buildExtension(models, baseUrl) {
  return [
    "// Generated by omnirouter launch: OmniRoute provider for pi, rebuilt on every launch. Do not edit.",
    `const MODELS = ${JSON.stringify(models, null, 2)};`,
    "",
    "export default function (pi) {",
    '  pi.registerProvider("omniroute", {',
    '    name: "OmniRoute",',
    `    baseUrl: ${JSON.stringify(baseUrl)},`,
    '    apiKey: "$OMNIROUTE_API_KEY",',
    '    api: "openai-completions",',
    "    models: MODELS,",
    "  });",
    "}",
    "",
  ].join("\n");
}

export default defineAdapter({
  contract: { major: 1, minor: 1 },
  id: "pi",
  displayName: DISPLAY_NAME,
  binaries: ["pi"],
  capabilities: {
    protocol: "openai-chat",
    modelList: {
      strategy: "inject",
      view: {
        name: "pi",
        filter: {
          protocols: ["openai-chat"],
          kinds: ["chat"],
          capabilities: ["tools"],
          minContextTokens: MIN_CONTEXT,
        },
        order: "preferences",
      },
    },
    minContextTokens: MIN_CONTEXT,
    model: "optional",
    versionGate: { args: ["--version"], min: MIN_VERSION },
    install: {
      commands: {
        any: [INSTALL_HINT],
        darwin: ["curl -fsSL https://pi.dev/install.sh | sh"],
        linux: ["curl -fsSL https://pi.dev/install.sh | sh"],
      },
      url: "https://pi.dev",
    },
    supportsProfile: false,
    platforms: ["darwin", "linux", "win32"],
    tier: "core",
    passthrough: [
      {
        flag: "--api-key",
        action: "warn",
        message: "--api-key replaces the OmniRoute session key and puts a key in argv",
      },
    ],
  },
  plan(ctx) {
    const warnings = [];
    const notes = [];

    const version = parseVersion(ctx.tool.version);
    if (version && compareVersions(version, parseVersion(MIN_VERSION)) < 0) {
      throw new LaunchError(
        "ToolVersionTooOld",
        `${DISPLAY_NAME} ${ctx.tool.version} is older than the minimum ${MIN_VERSION}`,
        { hint: INSTALL_HINT }
      );
    }

    if (ctx.view.rows.length === 0) {
      throw new LaunchError(
        "ModelNotFound",
        `No OmniRoute model matches the ${DISPLAY_NAME} view (tool-capable chat models, context >= 32000)`,
        { hint: "Check `omnirouter models` or relax the view" }
      );
    }

    const model = ctx.model ?? ctx.view.rows[0];
    if (!ctx.model) notes.push(`No model chosen: defaulting to ${model.id}`);
    if (typeof model.contextTokens === "number" && model.contextTokens < MIN_CONTEXT) {
      throw new LaunchError(
        "ModelUnsuitable",
        `${model.id} has a ${model.contextTokens}-token context; ${DISPLAY_NAME} needs at least ${MIN_CONTEXT}`
      );
    }

    const rows = injectRows(ctx);
    const models = rows.map(buildModel);
    const baseUrl = ctx.util.ensureV1(ctx.gateway.rootUrl);
    const keyless = ctx.auth.source === "none";

    const argv = ["-e", ctx.util.statePath("omniroute.ts")];
    const userPicksModel =
      findFlag(ctx.passthroughArgs, "--provider") !== null ||
      findFlag(ctx.passthroughArgs, "--model") !== null;
    if (!userPicksModel) argv.push("--provider", "omniroute", "--model", model.id);
    argv.push(...ctx.passthroughArgs);

    return createPlan("pi", {
      argv,
      env: {
        set: {
          OMNIROUTE_API_KEY: keyless ? NO_AUTH_SENTINEL : ctx.auth.token,
          PI_SKIP_VERSION_CHECK: "1",
        },
        unset: [],
      },
      tempFiles: [
        {
          path: "omniroute.ts",
          root: "state",
          mode: 0o600,
          format: "ts",
          contents: buildExtension(models, baseUrl),
        },
      ],
      secretSites: keyless ? [] : [{ kind: "env", key: "OMNIROUTE_API_KEY" }],
      notes,
      warnings,
      modelList: { strategy: "inject", viewHash: ctx.view.hash, injected: rows.length },
    });
  },
});
