// Shared plan pieces for inject-strategy adapters (pi, omp, opencode, kilo and friends).
// Pure: no fs, process or os reads.

import { LaunchError, findTokenSites, rowLabel } from "../../contract.mjs";
import { isSemverBelow } from "./semver.mjs";

/** The env var that carries the OmniRoute session key in most adapters. */
export const KEY_ENV = "OMNIROUTE_API_KEY";

/**
 * Throw ToolVersionTooOld when the probed version parses and is below `min`.
 * @param {{ tool: { version?: string | null } }} ctx
 * @param {{ displayName: string, min: string, hint: string }} gate
 */
export function assertMinVersion(ctx, { displayName, min, hint }) {
  if (isSemverBelow(ctx.tool.version, min)) {
    throw new LaunchError(
      "ToolVersionTooOld",
      `${displayName} ${ctx.tool.version} is older than the minimum ${min}`,
      { hint }
    );
  }
}

/**
 * The model for a tool-capable chat view: ctx.model, else the first view row (with a note).
 * Throws ModelNotFound on an empty view and ModelUnsuitable when the context is known and short.
 * @param {import("../../contract.d.ts").LaunchContext} ctx
 * @param {{ displayName: string, minContext: number, notes: string[] }} options
 */
export function pickToolModel(ctx, { displayName, minContext, notes }) {
  if (ctx.view.rows.length === 0) {
    throw new LaunchError(
      "ModelNotFound",
      `No OmniRoute model matches the ${displayName} view (tool-capable chat models, context >= 32000)`,
      { hint: "Check `omnirouter models` or relax the view" }
    );
  }
  const model = ctx.model ?? ctx.view.rows[0];
  if (!ctx.model) notes.push(`No model chosen: defaulting to ${model.id}`);
  if (typeof model.contextTokens === "number" && model.contextTokens < minContext) {
    throw new LaunchError(
      "ModelUnsuitable",
      `${model.id} has a ${model.contextTokens}-token context; ${displayName} needs at least ${minContext}`
    );
  }
  return model;
}

/**
 * secretSites for a plan whose only secret is env KEY_ENV (none when keyless).
 * @param {boolean} keyless
 */
export function keyEnvSites(keyless) {
  return keyless ? [] : [{ kind: "env", key: KEY_ENV }];
}

/**
 * The plan's modelList block for an inject adapter.
 * @param {import("../../contract.d.ts").LaunchContext} ctx
 * @param {number} injected
 */
export function injectModelList(ctx, injected) {
  return { strategy: "inject", viewHash: ctx.view.hash, injected };
}

/**
 * Set secretSites from every ${TOKEN} occurrence in the plan, then return it.
 * @param {import("../../contract.d.ts").LaunchPlan} plan
 */
export function withTokenSites(plan) {
  plan.secretSites = findTokenSites(plan);
  return plan;
}

/**
 * A pi.registerProvider model entry (pi and omp share this shape).
 * @param {import("../../contract.d.ts").LaunchModelRow} row
 * @param {{ contextWindow: number, maxTokens: number }} limits
 */
export function piModelEntry(row, { contextWindow, maxTokens }) {
  const caps = row.capabilities ?? [];
  return {
    id: row.id,
    name: rowLabel(row),
    reasoning: caps.includes("reasoning"),
    input: caps.includes("vision") ? ["text", "image"] : ["text"],
    cost: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0 },
    contextWindow,
    maxTokens,
  };
}

/**
 * The generated `-e` extension source that registers the "omniroute" provider.
 * @param {{ tool: string, models: object[], baseUrl: string, apiKey: string }} parts
 */
export function piExtension({ tool, models, baseUrl, apiKey }) {
  return [
    `// Generated by omnirouter launch: OmniRoute provider for ${tool}, rebuilt on every launch. Do not edit.`,
    `const MODELS = ${JSON.stringify(models, null, 2)};`,
    "",
    "export default function (pi) {",
    '  pi.registerProvider("omniroute", {',
    '    name: "OmniRoute",',
    `    baseUrl: ${JSON.stringify(baseUrl)},`,
    `    apiKey: ${JSON.stringify(apiKey)},`,
    '    api: "openai-completions",',
    "    models: MODELS,",
    "  });",
    "}",
    "",
  ].join("\n");
}

/**
 * Context and output limits for an OpenCode-family model entry.
 * @param {import("../../contract.d.ts").LaunchModelRow} row
 */
export function openCodeLimits(row) {
  const context = row.contextTokens ?? 128000;
  const output = row.maxOutputTokens ?? Math.min(32000, context);
  return { context, output };
}

/**
 * The OpenCode v1 / Kilo models map ({ name, tool_call, limit }), keyed by id in view order.
 * @param {import("../../contract.d.ts").LaunchModelRow[]} rows
 */
export function toolCallModels(rows) {
  const models = {};
  for (const row of rows) {
    models[row.id] = { name: rowLabel(row), tool_call: true, limit: openCodeLimits(row) };
  }
  return models;
}

/**
 * Serialize a config built from the injected rows, dropping rows from the END (the injected ids
 * stay a prefix of the view, in view order) until it fits `budget` bytes. The chosen model is
 * never dropped. Pushes a warning when rows were dropped.
 * @param {import("../../contract.d.ts").LaunchModelRow[]} allRows
 * @param {{ modelId: string, budget: number, build: (rows: import("../../contract.d.ts").LaunchModelRow[]) => string, warnings: string[] }} options
 * @returns {{ rows: import("../../contract.d.ts").LaunchModelRow[], content: string }}
 */
export function fitConfigToBudget(allRows, { modelId, budget, build, warnings }) {
  let rows = allRows;
  const minKeep = Math.max(1, rows.findIndex((row) => row.id === modelId) + 1);
  let content = build(rows);
  while (Buffer.byteLength(content) > budget && rows.length > minKeep) {
    rows = rows.slice(0, rows.length - 1);
    content = build(rows);
  }
  if (rows.length < allRows.length) {
    warnings.push(
      `Dropped ${allRows.length - rows.length} of ${allRows.length} models from the injected list: the ` +
        `config would exceed ${budget} bytes (the env var limit is 131072)`
    );
  }
  return { rows, content };
}
