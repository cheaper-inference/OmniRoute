// Oh My Pi (omp) launch adapter. Launch recipe: a `-e` extension that
// calls pi.registerProvider, plus an update-check overlay passed with --config.
import {
  ERROR_CODES,
  LaunchError,
  NO_AUTH_SENTINEL,
  createPlan,
  defineAdapter,
  ensureV1,
  hasFlag,
  injectRows,
  rowLabel,
} from "../contract.mjs";

const DISPLAY_NAME = "Oh My Pi";
const MIN_VERSION = "18.8.5";
const MIN_CONTEXT = 32000;
const INSTALL_HINT = "curl -fsSL https://omp.sh/install | sh";

function parseVersion(text) {
  const match = /(\d+)\.(\d+)\.(\d+)/.exec(String(text ?? ""));
  return match ? [Number(match[1]), Number(match[2]), Number(match[3])] : null;
}

function compareVersions(a, b) {
  for (let i = 0; i < 3; i += 1) {
    if (a[i] !== b[i]) return a[i] < b[i] ? -1 : 1;
  }
  return 0;
}

function buildModel(row) {
  const caps = row.capabilities ?? [];
  return {
    id: row.id,
    name: rowLabel(row),
    reasoning: caps.includes("reasoning"),
    input: caps.includes("vision") ? ["text", "image"] : ["text"],
    cost: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0 },
    contextWindow: row.contextTokens ?? 128000,
    maxTokens: row.maxOutputTokens ?? 32768,
  };
}

function buildExtension(models, baseUrl) {
  return [
    "// Generated by omnirouter launch: OmniRoute provider for omp, rebuilt on every launch. Do not edit.",
    `const MODELS = ${JSON.stringify(models, null, 2)};`,
    "",
    "export default function (pi) {",
    '  pi.registerProvider("omniroute", {',
    '    name: "OmniRoute",',
    `    baseUrl: ${JSON.stringify(baseUrl)},`,
    '    apiKey: "OMNIROUTE_API_KEY",',
    '    api: "openai-completions",',
    "    models: MODELS,",
    "  });",
    "}",
    "",
  ].join("\n");
}

export default defineAdapter({
  contract: { major: 1, minor: 1 },
  id: "omp",
  displayName: DISPLAY_NAME,
  binaries: ["omp"],
  capabilities: {
    protocol: "openai-chat",
    modelList: {
      strategy: "inject",
      view: {
        name: "omp",
        filter: {
          protocols: ["openai-chat"],
          kinds: ["chat"],
          capabilities: ["tools"],
          minContextTokens: MIN_CONTEXT,
        },
        order: "preferences",
      },
    },
    minContextTokens: MIN_CONTEXT,
    model: "optional",
    versionGate: { args: ["--version"], min: MIN_VERSION },
    install: {
      commands: {
        darwin: ["curl -fsSL https://omp.sh/install | sh"],
        linux: ["curl -fsSL https://omp.sh/install | sh"],
        win32: ["irm https://omp.sh/install.ps1 | iex"],
        any: ["bun install -g @oh-my-pi/pi-coding-agent"],
      },
      url: "https://omp.sh",
    },
    supportsProfile: false,
    platforms: ["darwin", "linux", "win32"],
    tier: "core",
    passthrough: [
      {
        flag: "--api-key",
        action: "warn",
        message:
          "--api-key did not override the provider key in testing; the OmniRoute session key stays in use",
      },
    ],
  },
  plan(ctx) {
    const notes = [];
    const warnings = [];

    const have = parseVersion(ctx.tool.version);
    const min = parseVersion(MIN_VERSION);
    if (have && min && compareVersions(have, min) < 0) {
      throw new LaunchError(
        ERROR_CODES.ToolVersionTooOld,
        `${DISPLAY_NAME} ${ctx.tool.version} is older than the minimum ${MIN_VERSION}`,
        { hint: INSTALL_HINT }
      );
    }

    if (ctx.view.rows.length === 0) {
      throw new LaunchError(
        ERROR_CODES.ModelNotFound,
        `No OmniRoute model matches the ${DISPLAY_NAME} view (tool-capable chat models, context >= 32000)`,
        { hint: "Check `omnirouter models` or relax the view" }
      );
    }

    const model = ctx.model ?? ctx.view.rows[0];
    if (!ctx.model) notes.push(`No model chosen: defaulting to ${model.id}`);
    if (typeof model.contextTokens === "number" && model.contextTokens < MIN_CONTEXT) {
      throw new LaunchError(
        ERROR_CODES.ModelUnsuitable,
        `${model.id} has a ${model.contextTokens}-token context; ${DISPLAY_NAME} needs at least ${MIN_CONTEXT}`
      );
    }

    const rows = injectRows(ctx);
    const models = rows.map(buildModel);
    const extension = buildExtension(models, ensureV1(ctx.gateway.rootUrl));
    const noAuth = ctx.auth.source === "none";

    const args = ctx.passthroughArgs;
    const argv = ["-e", "${STATE}/omniroute.ts", "--config", "${TMP}/omp-overlay.yml"];
    const userModel = hasFlag(args, ["--model"]);
    const legacyProvider = hasFlag(args, ["--provider"]);
    if (!userModel && !legacyProvider) argv.push("--model", `omniroute/${model.id}`);
    if (legacyProvider && !userModel) {
      notes.push("--provider is legacy: your --provider choice is kept and no --model was added");
    }
    argv.push(...args);

    notes.push(
      "omp models may not list the OmniRoute provider (extensions load only for sessions); use /model inside omp"
    );

    return createPlan("omp", {
      argv,
      env: {
        set: { OMNIROUTE_API_KEY: noAuth ? NO_AUTH_SENTINEL : ctx.auth.token },
        unset: [],
      },
      tempFiles: [
        { path: "omniroute.ts", root: "state", mode: 0o600, format: "ts", contents: extension },
        {
          path: "omp-overlay.yml",
          mode: 0o600,
          format: "yaml",
          contents: ctx.util.yaml({ startup: { checkUpdate: false } }),
        },
      ],
      needsTempDir: true,
      secretSites: noAuth ? [] : [{ kind: "env", key: "OMNIROUTE_API_KEY" }],
      notes,
      warnings,
      modelList: { strategy: "inject", viewHash: ctx.view.hash, injected: rows.length },
    });
  },
});
