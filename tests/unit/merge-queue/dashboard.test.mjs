test("computeMetrics joins approvals with landings (median, p90, CI runs per PR)", () => {
  const s = state({
    counters: {
      ...initialState(BASE).counters,
      ciRuns: 7,
      landedPrs: 4,
      redBatches: 2,
      bisections: 1,
    },
    history: [
      {
        at: "2026-11-13T10:00:00Z",
        type: "batch-started",
        prs: [1, 2],
        labeledAt: { 1: "2026-11-13T09:30:00Z", 2: "2026-11-13T08:30:00Z" },
      },
      { at: "2026-11-13T11:00:00Z", type: "landed", prs: [1, 2] }, // 90, 150
      {
        at: "2026-11-13T11:05:00Z",
        type: "batch-started",
        prs: [3],
        labeledAt: { 3: "2026-11-13T08:00:00Z" },
      },
      { at: "2026-11-13T11:30:00Z", type: "checks-red", prs: [3] },
      {
        at: "2026-11-13T11:40:00Z",
        type: "batch-started",
        prs: [3],
        labeledAt: { 3: "2026-11-13T11:30:00Z" }, // re-approved: the latest approval wins
      },
      { at: "2026-11-13T12:00:00Z", type: "landed", prs: [3] }, // 30
      { at: "2026-11-13T12:10:00Z", type: "landed", prs: [4] }, // approval unknown → skipped
      {
        at: "2026-11-13T12:20:00Z",
        type: "batch-started",
        prs: [5],
        labeledAt: { 5: "2026-11-13T02:20:00Z" },
      },
      { at: "2026-11-13T12:20:00Z", type: "landed", prs: [5] }, // 600
    ],
  });
  assert.deepEqual(computeMetrics(s, NOW), {
    landedPrs: 4,
    ciRunsPerMergedPr: 1.8,
    redBatches: 2,
    bisections: 1,
    medianLabelToMergeMinutes: 120, // [30, 90, 150, 600] → (90 + 150) / 2
    p90LabelToMergeMinutes: 600,
  });
});

test("computeMetrics: empty state, in-flight fallback and shadow would-land", () => {
  assert.deepEqual(computeMetrics(state(), NOW), {
    landedPrs: 0,
    ciRunsPerMergedPr: null,
    redBatches: 0,
    bisections: 0,
    medianLabelToMergeMinutes: null,
    p90LabelToMergeMinutes: null,
  });
  const shadow = state({
    inFlight: {
      batchId: "b3",
      kind: "batch",
      candidateRef: `omni-queue/release-v3.8.54/b3-${sha("c").slice(0, 12)}`,
      candidateSha: sha("c"),
      baseSha: sha("b"),
      treeSha: null,
      prs: [],
      stage: "testing",
      startedAt: "2026-11-13T10:00:00Z",
      attempts: 0,
      bisect: {
        rootBatchId: "b2",
        segments: [[pr(8, "t", "a", "2026-11-13T09:00:00Z")]],
        culprits: [],
        landed: [],
        steps: 1,
      },
    },
    history: [
      { at: "2026-11-13T09:45:00Z", type: "would-land", prs: [8] },
      { at: "2026-11-13T09:50:00Z", type: "would-land", prs: [8, 99] },
    ],
  });
  const m = computeMetrics(shadow, NOW);
  assert.equal(m.medianLabelToMergeMinutes, 47.5);
  assert.equal(m.p90LabelToMergeMinutes, 50);
  // once a real landing exists, would-land events no longer count
  shadow.history.push({ at: "2026-11-13T10:30:00Z", type: "landed", prs: [8] });
  assert.equal(computeMetrics(shadow, NOW).medianLabelToMergeMinutes, 90);
});

