test("renderDashboard escapes malicious titles, details and URLs", () => {
  const title = "pwn | col [x](http://evil) <img src=x onerror=alert(1)> @user";
  const body = renderDashboard({
    base: BASE,
    state: state({
      history: [
        {
          at: NOW,
          type: "pr-dequeued",
          prs: [40],
          detail: `conflict in ${title}`,
          url: "javascript:alert(1)",
        },
      ],
    }),
    queue: [
      {
        number: 40,
        title,
        author: "@evil<script>",
        eligible: false,
        reasons: [{ code: "draft", detail: "[click](http://evil) | @owner" }],
        labeledAt: null,
      },
    ],
    config: live,
    now: NOW,
    runUrl: "https://evil.example/x) [y](z",
  });
  assert.ok(!body.includes("<img"));
  assert.ok(!body.includes("<script"));
  assert.ok(!/\]\(http:\/\/evil/.test(body), "no markdown link to evil");
  assert.ok(!/(^|[^&#0-9])@(user|owner|evil)/m.test(body), "no live mention");
  assert.ok(!body.includes("javascript:"), "unsafe event URL dropped");
  assert.ok(!body.includes("evil.example"), "unsafe run URL dropped");
  const row = body.split("\n").find((l) => l.startsWith("| 1 | #40"));
  // 5 columns → exactly 6 unescaped pipes
  assert.equal(row.match(/(?<!\\)\|/g).length, 6, row);
  assert.ok(row.includes("| evilscript |"), "author reduced to login characters");
  const eventRow = body.split("\n").find((l) => l.includes("`pr-dequeued`"));
  assert.equal(eventRow.match(/(?<!\\)\|/g).length, 6, eventRow);
});

