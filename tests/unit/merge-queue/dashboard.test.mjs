test("escapeMarkdown neutralizes links, tables, HTML, mentions and autolinks", () => {
  const evil = "fix | [x](http://evil) <img src=x onerror=alert(1)> @user www.evil.io `c`";
  const out = escapeMarkdown(evil);
  assert.equal(
    out,
    "fix \\| \\[x\\]\\(http:&#8203;//evil\\) &lt;img src=x onerror=alert\\(1\\)&gt; " +
      "@&#8203;user www&#8203;.evil.io \\`c\\`"
  );
  assert.ok(!out.includes("<img"));
  assert.ok(!/(^|[^\\])\|/.test(out), "every pipe is escaped");
  assert.ok(!/\]\(http/.test(out), "no markdown link survives");
  assert.ok(!/@[A-Za-z]/.test(out), "no live mention");
  assert.equal(escapeMarkdown("line1\nline2\r\n\tx"), "line1 line2 x");
  assert.equal(escapeMarkdown("a".repeat(300), 10), "aaaaaaa...");
  assert.equal(escapeMarkdown(null), "");
});

test("formatDuration renders minutes and hours", () => {
  assert.equal(formatDuration(null), "—");
  assert.equal(formatDuration(42.4), "42 min");
  assert.equal(formatDuration(120), "2 h");
  assert.equal(formatDuration(135), "2 h 15 min");
});

