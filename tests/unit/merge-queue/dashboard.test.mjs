test("upsertDashboard creates once, updates only on change, ignores look-alikes", async (t) => {
  const fake = await startFakeGitHub({ token: "tkn" });
  t.after(() => fake.close());
  const gh = createGitHubClient({ token: "tkn", repository: fake.repository, apiUrl: fake.url });
  fake.addIssue({ number: 1, title: dashboardTitle(BASE), labels: [] }); // no label → ignored
  fake.addIssue({ number: 2, title: `${dashboardTitle(BASE)} (old)`, labels: [DASHBOARD_LABEL] });
  fake.addIssue({
    number: 3,
    title: dashboardTitle(BASE),
    labels: [DASHBOARD_LABEL],
    state: "closed",
  });

  const n = await upsertDashboard({ gh, base: BASE, body: "v1" });
  assert.ok(![1, 2, 3].includes(n));
  const created = fake.issues.get(n);
  assert.equal(created.title, dashboardTitle(BASE));
  assert.deepEqual(
    created.labels.map((l) => l.name),
    [DASHBOARD_LABEL]
  );
  assert.equal(created.body, "v1");

  const patches = () => fake.requests.filter((r) => r.method === "PATCH").length;
  assert.equal(await upsertDashboard({ gh, base: BASE, body: "v1" }), n);
  assert.equal(patches(), 0, "unchanged body → no write");
  assert.equal(await upsertDashboard({ gh, base: BASE, body: "v2" }), n);
  assert.equal(patches(), 1);
  assert.equal(fake.issues.get(n).body, "v2");
  assert.equal(fake.requests.filter((r) => r.method === "POST" && r.path === "/issues").length, 1);

  const other = await upsertDashboard({ gh, base: "release/v3.8.55", body: "x" });
  assert.notEqual(other, n, "one dashboard per base");
});
