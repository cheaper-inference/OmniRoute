import assert from "node:assert/strict";
import test from "node:test";
import { buildSkillMarkdown } from "../../src/lib/agentSkills/generator.ts";
import { parseCliRegistry } from "../../src/lib/agentSkills/cliRegistryParser.ts";

// Asserts on what the generator writes for cli-keys, not on the committed skills/cli-keys/SKILL.md:
// that file is derived and the release refresh rewrites it, so a feature PR cannot keep it in step.
test("generated cli-keys skill matches the authenticated key-policy command registry", () => {
  const { body } = buildSkillMarkdown("cli-keys", {
    openapi: { paths: new Map(), areas: new Map() },
    cliRegistry: parseCliRegistry(),
  });
  const headings = body.split("\n").filter((line) => line.startsWith("### "));

  // The output is the generator's own, with its marker, so the release refresh owns it.
  assert.match(body, /<!-- generated by src\/lib\/agentSkills\/generator\.ts/);
  // Nested commands carry their full group path: the policy command is `keys policy set`, not `keys set`.
  assert.ok(headings.includes("### `keys policy set <id>`"), "keys policy set must be documented");
  assert.equal(
    headings.includes("### `keys set <id>`"),
    false,
    "a nested command must not lose its group path"
  );

  const policy = body.split("### `keys policy set <id>`\n")[1]?.split("\n### ")[0];
  assert.ok(policy, "the key-policy command must remain documented");
  assert.match(policy, /- `--allowed-models <list>`/);
  assert.match(policy, /- `--model-access-mode <mode>`/);
  assert.match(policy, /- `--unrestricted`/);
});
