import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import test from "node:test";
import { fileURLToPath } from "node:url";

import {
  categoryOf,
  evaluateDerivedPaths,
  loadFamilies,
} from "../../scripts/check/check-pr-derived-paths.mjs";

// The "generated" and "baselines" families (config/quality/derived-paths/) keep feature PRs
// from carrying files a refresh rewrites (plan 2026-11-13, phase 5). These tests keep the
// declarations exact: a path that is not really generated would block a legitimate hand edit,
// a generated file missing from the list would keep conflicting across PRs.

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const families = loadFamilies(root);
const generated = families.find((f) => f.family === "generated");
const baselines = families.find((f) => f.family === "baselines");
const category = (family: typeof generated, id: string) =>
  family?.categories.find((c) => c.id === id);
const GENERATED_MARKER = "<!-- generated by src/lib/agentSkills/generator.ts";
const CUSTOM_START = "<!-- skill:custom-start -->";

test("both families load and name the release branches as writers", () => {
  assert.ok(generated, "config/quality/derived-paths/generated.json");
  assert.ok(baselines, "config/quality/derived-paths/baselines.json");
  for (const family of [generated, baselines]) {
    assert.ok(family.writers.includes("release/v*"), `${family.family}: release/v* writes it`);
    assert.ok(family.writers.includes("chore/derived-*"), `${family.family}: nightly refresh`);
    assert.ok(family.companions.includes("changelog.d/**"));
  }
});

test("readme-diagrams lists exactly the SVGs the README driver generates", () => {
  const driver = fs.readFileSync(path.join(root, "scripts/docs/gen-readme-diagrams.mjs"), "utf8");
  const outs = [...driver.matchAll(/out: "(docs\/diagrams\/[\w.-]+\.svg)"/g)].map((m) => m[1]);
  assert.ok(outs.length >= 12, `driver outputs parsed: ${outs.length}`);
  assert.deepEqual([...category(generated, "readme-diagrams").paths].sort(), [...outs].sort());
});

test("hand-drawn SVGs and the Mermaid exports are not claimed as generated", () => {
  for (const file of [
    "docs/diagrams/pool-fair-share.svg",
    "docs/diagrams/combo-always-on.svg",
    "docs/diagrams/exported/request-pipeline.svg",
    "public/images/tier-flow-dark.svg",
    "public/images/tier-flow-light.svg",
  ]) {
    assert.equal(categoryOf(file, generated), null, file);
  }
});

test("agent-skills-generated lists exactly the SKILL.md files the generator writes in full", () => {
  const expected = fs
    .readdirSync(path.join(root, "skills"), { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => `skills/${entry.name}/SKILL.md`)
    .filter((file) => fs.existsSync(path.join(root, file)))
    .filter((file) => {
      const text = fs.readFileSync(path.join(root, file), "utf8");
      return text.includes(GENERATED_MARKER) && !text.includes(CUSTOM_START);
    })
    .sort();
  assert.ok(expected.length > 0);
  assert.deepEqual([...category(generated, "agent-skills-generated").paths].sort(), expected);
});

test("a SKILL.md with a hand-written custom block stays editable next to a feature", () => {
  const withCustom = fs
    .readdirSync(path.join(root, "skills"))
    .map((id) => `skills/${id}/SKILL.md`)
    .filter((file) => fs.existsSync(path.join(root, file)))
    .filter((file) => fs.readFileSync(path.join(root, file), "utf8").includes(CUSTOM_START));
  assert.ok(withCustom.length > 0);
  for (const file of withCustom) assert.equal(categoryOf(file, generated), null, file);
  assert.equal(categoryOf("skills/README.md", generated), null);
});

test("every exact path of both families exists on disk", () => {
  for (const family of [generated, baselines]) {
    for (const cat of family.categories) {
      for (const p of cat.paths.filter((p) => !p.includes("*"))) {
        assert.ok(fs.existsSync(path.join(root, p)), `${family.family}/${cat.id}: ${p}`);
      }
    }
  }
});

