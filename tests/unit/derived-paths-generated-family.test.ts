test("a provider PR that regenerates the reference fails; the generator-only PR passes", () => {
  const providerPr = evaluateDerivedPaths({
    files: [
      "src/shared/constants/providers.ts",
      "docs/reference/PROVIDER_REFERENCE.md",
      "docs/diagrams/readme-hero.svg",
      "changelog.d/features/1-x.md",
    ],
    branch: "feat/new-provider",
    families,
  });
  assert.deepEqual(
    providerPr.violations.map((v) => v.category),
    ["provider-reference", "readme-diagrams"]
  );

  const generatorPr = evaluateDerivedPaths({
    files: [
      "scripts/docs/gen-readme-hero.mjs",
      "tests/unit/docs/readme-hero-svg.test.ts",
      "docs/diagrams/readme-hero.svg",
    ],
    branch: "fix/hero-layout",
    families,
  });
  assert.deepEqual(generatorPr.violations, []);

  const refresh = evaluateDerivedPaths({
    files: ["src/app/page.tsx", "docs/reference/PROVIDER_REFERENCE.md"],
    branch: "release/v3.8.55",
    families,
  });
  assert.deepEqual(refresh.violations, []);
});

test("a feature PR that adds an e2e spec does not have to touch e2e-timings.json", () => {
  const withTimings = evaluateDerivedPaths({
    files: ["tests/e2e/new-flow.spec.ts", "config/quality/e2e-timings.json"],
    branch: "feat/flow",
    families,
  });
  assert.deepEqual(
    withTimings.violations.map((v) => `${v.family}/${v.category}`),
    ["baselines/e2e-timings"]
  );
  const banking = evaluateDerivedPaths({
    files: ["config/quality/e2e-timings.json"],
    branch: "chore/bank-ratchet-v3.8.55",
    families,
  });
  assert.deepEqual(banking.violations, []);
});

test(".gitattributes collapses the generated diffs, but never an agent-instruction file", () => {
  const attr = (files: string[]) =>
    execFileSync("git", ["check-attr", "linguist-generated", "--", ...files], {
      cwd: root,
      encoding: "utf8",
    })
      .trim()
      .split("\n")
      .map((line) => line.split(": ").pop());
  const collapsed = [
    ...category(generated, "provider-reference").paths,
    ...category(generated, "readme-diagrams").paths,
    "skills/omni-inference/references/endpoints.md",
    ".i18n-state.json",
  ];
  assert.deepEqual(
    attr(collapsed),
    collapsed.map(() => "true")
  );
  const visible = [
    ...category(generated, "agent-skills-generated").paths.slice(0, 3),
    "skills/omni-inference/SKILL.md",
    "llm.txt",
    "docs/i18n/pt-BR/llm.txt",
    "AGENTS.md",
  ];
  assert.deepEqual(
    attr(visible),
    visible.map(() => "unspecified")
  );
});
