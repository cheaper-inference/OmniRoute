// Unit tests for bin/cli/launch/adapters/_shared/inject.mjs (shared inject-adapter plan pieces).

import { test } from "node:test";
import assert from "node:assert/strict";

import { LaunchError, createPlan } from "../../../../../bin/cli/launch/contract.mjs";
import {
  KEY_ENV,
  assertMinVersion,
  fitConfigToBudget,
  injectModelList,
  keyEnvSites,
  openCodeLimits,
  piExtension,
  piModelEntry,
  pickToolModel,
  toolCallModels,
  withTokenSites,
} from "../../../../../bin/cli/launch/adapters/_shared/inject.mjs";

type Row = {
  id: string;
  label?: string;
  contextTokens?: number;
  maxOutputTokens?: number;
  capabilities?: string[];
};

function ctxWith(rows: Row[], model?: Row, version = "1.0.0") {
  return {
    tool: { version },
    model: model ?? null,
    view: { rows, hash: "h1" },
  } as never;
}

function codeOf(fn: () => void): string {
  try {
    fn();
  } catch (error) {
    assert.ok(error instanceof LaunchError);
    return (error as LaunchError).code;
  }
  return "none";
}

test("assertMinVersion throws ToolVersionTooOld only for a parsed version below min", () => {
  const gate = { displayName: "Tool", min: "1.2.0", hint: "upgrade" };
  assert.throws(
    () => assertMinVersion(ctxWith([], undefined, "1.1.9"), gate),
    (error: LaunchError) =>
      error.code === "ToolVersionTooOld" &&
      error.message === "Tool 1.1.9 is older than the minimum 1.2.0" &&
      error.hint === "upgrade"
  );
  assert.doesNotThrow(() => assertMinVersion(ctxWith([], undefined, "1.2.0"), gate));
  assert.doesNotThrow(() => assertMinVersion(ctxWith([], undefined, "vunknown"), gate));
});

test("pickToolModel defaults to the first row with a note and checks the context", () => {
  const rows = [{ id: "a", contextTokens: 64000 }, { id: "b" }];
  const options = { displayName: "Tool", minContext: 32000, notes: [] as string[] };
  assert.equal(pickToolModel(ctxWith(rows), options).id, "a");
  assert.deepEqual(options.notes, ["No model chosen: defaulting to a"]);

  const chosen = { displayName: "Tool", minContext: 32000, notes: [] as string[] };
  assert.equal(pickToolModel(ctxWith(rows, rows[1]), chosen).id, "b");
  assert.deepEqual(chosen.notes, []);

  assert.equal(
    codeOf(() => pickToolModel(ctxWith([]), options)),
    "ModelNotFound"
  );
  const short = { id: "s", contextTokens: 8000 };
  assert.throws(
    () => pickToolModel(ctxWith([short], short), options),
    (error: LaunchError) =>
      error.code === "ModelUnsuitable" &&
      error.message === "s has a 8000-token context; Tool needs at least 32000"
  );
});

test("keyEnvSites, injectModelList and withTokenSites build plan parts", () => {
  assert.equal(KEY_ENV, "OMNIROUTE_API_KEY");
  assert.deepEqual(keyEnvSites(true), []);
  assert.deepEqual(keyEnvSites(false), [{ kind: "env", key: "OMNIROUTE_API_KEY" }]);
  assert.deepEqual(injectModelList(ctxWith([]), 3), {
    strategy: "inject",
    viewHash: "h1",
    injected: 3,
  });
  const plan = withTokenSites(
    createPlan("x", { env: { set: { K: "${TOKEN}", O: "plain" }, unset: [] } })
  );
  assert.deepEqual(plan.secretSites, [{ kind: "env", key: "K" }]);
});

test("piModelEntry maps capabilities and the given limits", () => {
  const entry = piModelEntry(
    { id: "m", label: "M", capabilities: ["reasoning", "vision"] } as Row as never,
    { contextWindow: 1000, maxTokens: 10 }
  );
  assert.equal(entry.id, "m");
  assert.equal(entry.reasoning, true);
  assert.deepEqual(entry.input, ["text", "image"]);
  assert.deepEqual(entry.cost, { input: 0, output: 0, cacheRead: 0, cacheWrite: 0 });
  assert.equal(entry.contextWindow, 1000);
  assert.equal(entry.maxTokens, 10);
  const plain = piModelEntry({ id: "p" } as Row as never, { contextWindow: 1, maxTokens: 1 });
  assert.equal(plain.reasoning, false);
  assert.deepEqual(plain.input, ["text"]);
});

test("piExtension renders the provider registration with the given key reference", () => {
  const source = piExtension({
    tool: "pi",
    models: [{ id: "m" }],
    baseUrl: "http://127.0.0.1:1/v1",
    apiKey: "$OMNIROUTE_API_KEY",
  });
  assert.match(source, /^\/\/ Generated by omnirouter launch: OmniRoute provider for pi,/);
  assert.ok(source.includes('    baseUrl: "http://127.0.0.1:1/v1",\n'));
  assert.ok(source.includes('    apiKey: "$OMNIROUTE_API_KEY",\n'));
  assert.ok(source.includes('const MODELS = [\n  {\n    "id": "m"\n  }\n];'));
  assert.ok(source.endsWith("}\n"));
});

test("openCodeLimits and toolCallModels default the limits", () => {
  assert.deepEqual(openCodeLimits({ id: "a" } as never), { context: 128000, output: 32000 });
  assert.deepEqual(openCodeLimits({ id: "a", contextTokens: 8000 } as never), {
    context: 8000,
    output: 8000,
  });
  const models = toolCallModels([
    { id: "b", contextTokens: 64000, maxOutputTokens: 100 },
    { id: "a" },
  ] as never);
  assert.deepEqual(Object.keys(models), ["b", "a"]);
  assert.deepEqual(models.b.limit, { context: 64000, output: 100 });
  assert.equal(models.b.tool_call, true);
});

test("fitConfigToBudget drops rows from the end but keeps the chosen model", () => {
  const rows = [{ id: "a" }, { id: "b" }, { id: "c" }, { id: "d" }] as never[];
  const build = (list: Array<{ id: string }>) => "x".repeat(list.length * 10);

  const fits: string[] = [];
  const all = fitConfigToBudget(rows, { modelId: "a", budget: 100, build, warnings: fits });
  assert.equal(all.rows.length, 4);
  assert.equal(all.content.length, 40);
  assert.deepEqual(fits, []);

  const warnings: string[] = [];
  const cut = fitConfigToBudget(rows, { modelId: "a", budget: 25, build, warnings });
  assert.deepEqual(
    cut.rows.map((row: { id: string }) => row.id),
    ["a", "b"]
  );
  assert.deepEqual(warnings, [
    "Dropped 2 of 4 models from the injected list: the config would exceed 25 bytes (the env var limit is 131072)",
  ]);

  const kept = fitConfigToBudget(rows, { modelId: "c", budget: 5, build, warnings: [] });
  assert.deepEqual(
    kept.rows.map((row: { id: string }) => row.id),
    ["a", "b", "c"]
  );
});
